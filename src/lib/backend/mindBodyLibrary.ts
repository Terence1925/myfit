import type { FocusArea } from '../types'
import type { LibraryExercise, MindBodyPhase } from './exerciseLibrary'

// Yoga and mat Pilates. Poses are beginner-friendly versions with a note on how to make them easier.
//
// `lowImpactSafe` lists the injuries a move is generally gentle enough for. It is deliberately
// conservative: with an injury selected, a move is only offered if it is tagged safe for it, so
// anything uncertain is left out rather than risked.

type Joint = 'knee' | 'shoulder' | 'lower-back'
const ALL: Joint[] = ['knee', 'shoulder', 'lower-back']

type Options = Partial<Pick<LibraryExercise, 'timing' | 'eachSide' | 'level' | 'fixedReps' | 'equipment'>>

function yoga(
  name: string,
  muscle: FocusArea[],
  phases: MindBodyPhase[],
  safe: Joint[],
  cue: string,
  o: Options = {},
): LibraryExercise {
  return {
    name,
    equipment: ['yoga'],
    muscle,
    compound: muscle.length > 2 || muscle.includes('full-body'),
    lowImpactSafe: safe,
    phases,
    timing: 'hold',
    level: 'beginner',
    cue,
    ...o,
  }
}

function pilates(
  name: string,
  muscle: FocusArea[],
  phases: MindBodyPhase[],
  safe: Joint[],
  cue: string,
  o: Options = {},
): LibraryExercise {
  return {
    name,
    equipment: ['pilates'],
    muscle,
    compound: muscle.length > 2 || muscle.includes('full-body'),
    lowImpactSafe: safe,
    phases,
    timing: 'reps',
    level: 'beginner',
    cue,
    ...o,
  }
}

